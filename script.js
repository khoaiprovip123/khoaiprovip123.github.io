let lang = localStorage.getItem('vk-lang') || (navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en');
const langToggle = document.getElementById('langToggle');
function applyLang(next){
  lang = next; document.documentElement.lang = next; localStorage.setItem('vk-lang', next);
  document.querySelectorAll('[data-i18n]').forEach(el=>{const key=el.dataset.i18n;if(i18n[next][key]) el.textContent=i18n[next][key];});
  langToggle.setAttribute('aria-pressed', String(next==='en'));
  langToggle.innerHTML = next==='vi' ? '<span class="active">VI</span><span>/</span><span>EN</span>' : '<span>VI</span><span>/</span><span class="active">EN</span>';
}
langToggle?.addEventListener('click',()=>{
  const next = lang==='vi'?'en':'vi';
  if(document.startViewTransition){
    document.startViewTransition(()=>applyLang(next));
  }else{
    applyLang(next);
  }
});
applyLang(lang);

